  function fill(str, ctx) {
    if (!ctx) return str;
    return str.replace(/\{(\w+)\}/g, (m, k) => (ctx[k] != null ? ctx[k] : m));
  }
  const counters = {};
  /** 같은 키의 대사를 순환하며 고른다 (반복 느낌 줄이기). */
  function pick(key, ctx, raceId) {
    let pool = null;
    if (raceId && LINES.races[raceId] && LINES.races[raceId][key]) pool = LINES.races[raceId][key];
    else if (LINES.common[key]) pool = LINES.common[key];
    if (!pool || !pool.length) return '';
    const ck = (raceId || '') + ':' + key;
    const i = (counters[ck] = (counters[ck] || 0) + 1) - 1;
    return fill(pool[i % pool.length], ctx);
  }
  function has(key, raceId) {
    return !!(raceId && LINES.races[raceId] && LINES.races[raceId][key]);
  }

  /** 경기별 시간 트리거 대사 [{at: 1위 도착 시간 대비 비율, text}] — 코드가 아니라 여기서 관리 */
  function timed(raceId) {
    const r = LINES.races[raceId];
    return r && r.timed ? r.timed.map(t => ({ at: t.at, text: t.text, done: false })) : [];
  }

  const Otter = { name: '해달 캐스터', LINES, pick, has, fill, timed };
  if (typeof module !== 'undefined' && module.exports) module.exports = Otter;
  global.Otter = Otter;
